#!/usr/bin/env python3
"""Inventory the IOP modules (R3000) shipped on the disc (Phase 6 step 6).

Records architecture/size/identity only - no game bytes are written.

    python3 tools/iop_inventory.py            # prints and writes manifest/iop_modules.txt
"""
from __future__ import annotations

import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEARCH = [ROOT / "extracted" / "MODULES", ROOT / "extracted" / "MODULES2",
          ROOT / "extracted"]
OUT = ROOT / "manifest" / "iop_modules.txt"

EM = {8: "EM_MIPS", 3: "EM_386"}
ARCH_FLAGS = {
    0x00000000: "MIPS-I", 0x00100000: "MIPS-II", 0x00200000: "MIPS-III",
    0x00300000: "MIPS-IV", 0x00400000: "MIPS-V",
}


def describe(path: Path) -> dict:
    data = path.read_bytes()
    sha256 = hashlib.sha256(data).hexdigest()
    d = {"name": path.name, "bytes": len(data), "sha256": sha256,
         "elf": False}
    if data[:4] != b"\x7fELF":
        return d
    d["elf"] = True
    cls, endian = data[4], data[5]
    e_type, e_machine, e_version, e_entry, e_phoff, e_shoff, e_flags = (
        struct.unpack_from("<HHIIII I".replace(" ", ""), data, 16))
    d.update({
        "class": {1: "ELF32", 2: "ELF64"}.get(cls, cls),
        "endian": {1: "little", 2: "big"}.get(endian, endian),
        "type": {1: "REL", 2: "EXEC", 3: "DYN"}.get(e_type, e_type),
        "machine": EM.get(e_machine, f"0x{e_machine:x}"),
        "entry": f"0x{e_entry:08X}",
        "flags": f"0x{e_flags:08X}",
        "arch": ARCH_FLAGS.get(e_flags & 0x00F00000, "?"),
    })
    return d


def main() -> int:
    found: dict[str, dict] = {}
    for d in SEARCH:
        if not d.is_dir():
            continue
        for p in sorted(d.glob("*.IRX")):
            found.setdefault(p.name, describe(p))
        for p in sorted(d.glob("*.irx")):
            found.setdefault(p.name, describe(p))

    lines = ["# IOP modules (R3000) shipped on the disc - inventory only",
             "# generated by tools/iop_inventory.py",
             ""]
    print(f"{len(found)} IOP module(s)")
    for name in sorted(found):
        info = found[name]
        if not info["elf"]:
            line = f"{name:<14} {info['bytes']:>8} bytes  (not ELF)  sha256:{info['sha256'][:16]}"
        else:
            line = (f"{name:<14} {info['bytes']:>8} bytes  {info['class']} "
                    f"{info['endian']} {info['machine']} arch={info['arch']} "
                    f"entry={info['entry']} flags={info['flags']} "
                    f"sha256:{info['sha256'][:16]}")
        print("  " + line)
        lines.append(line)
    lines.append("")
    lines.append("All are IOP (R3000A) binaries: a *separate* target from the EE")
    lines.append("(R5900) main executable. Not part of the EE decompilation scope;")
    lines.append("recorded for completeness (AGENTS.md step 6).")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
