#!/usr/bin/env python3
"""Generate a splat PS2 config for SCUS_974.72 using splat's own PS2 ELF parser.

splat's `create_config` runs `objcopy -O binary` to make a flat ROM before it can
emit the YAML, and MinGW's objcopy cannot read a MIPS ELF. This script calls the
same `splat.util.ps2.ps2elfinfo.Ps2Elf.get_info` directly and reproduces
`create_config.do_elf`'s header, so the resulting config is identical to what
splat would have produced.

Run with the project venv python (splat must be importable):
    .venv\\Scripts\\python.exe tools/splat_ps2_config.py <elf> <rom> <out.yaml>
"""

from __future__ import annotations

import hashlib
import os
import sys
from pathlib import Path

from splat.util.ps2 import ps2elfinfo  # provided by the project venv


def main(elf_path: str, rom_path: str, out_yaml: str) -> None:
    elf_bytes = Path(elf_path).read_bytes()
    elf = ps2elfinfo.Ps2Elf.get_info(Path(elf_path), elf_bytes)
    if elf is None:
        raise SystemExit("splat's PS2 parser rejected the ELF")

    basename = Path(elf_path).name.replace(" ", "")
    cleaned_basename = "".join(c for c in basename if c not in '<>:"/\\|?*')
    sha1 = hashlib.sha1(Path(rom_path).read_bytes()).hexdigest()

    rom_name = rom_path.replace("\\", "/")
    header = f"""\
# name: Shadow of the Colossus (USA) -- main ELF
# Generated by tools/splat_ps2_config.py (splat ps2elfinfo); edit as needed.
sha1: {sha1}
options:
  basename: {basename}
  target_path: {rom_name}
  elf_path: build/{cleaned_basename}.elf
  base_path: ..
  platform: ps2
  compiler: {elf.compiler}
"""
    if elf.gp is not None:
        header += f"  gp_value: 0x{elf.gp:08X}\n"
        if elf.ld_gp_expression is not None:
            header += f"  ld_gp_expression: {elf.ld_gp_expression}\n"

    header += f"""
  asm_path: asm
  src_path: src
  build_path: build

  ld_script_path: build/{cleaned_basename}.ld
  ld_dependencies: True
  ld_wildcard_sections: True
  ld_bss_contains_common: True

  create_asm_dependencies: True
  find_file_boundaries: False
  o_as_suffix: True

  symbol_addrs_path:
    - config/symbol_addrs.txt
  reloc_addrs_path:
    - config/reloc_addrs.txt

  string_encoding: ASCII
  data_string_encoding: ASCII
  rodata_string_guesser_level: 2
  data_string_guesser_level: 2
  named_regs_for_c_funcs: False
"""

    header += "\n  section_order:\n"
    for sect, is_valid in elf.elf_section_names:
        header += f"    {'' if is_valid else '# '}- {sect}\n"

    header += "\n  auto_link_sections:\n"
    for sect, is_valid in elf.elf_section_names:
        if sect in (".text", ".vutext"):
            continue
        header += f"    {'' if is_valid else '# '}- {sect}\n"

    segments = "\nsegments:"
    for seg in elf.segs:
        segments += (
            f"\n  - name: {seg.name}\n"
            f"    type: code\n"
            f"    start: 0x{seg.start:06X}\n"
            f"    vram: 0x{seg.vram:08X}\n"
            f"    bss_size: 0x{seg.bss_size:X}\n"
            f"    subalign: null\n"
            f"    subsegments:\n"
        )
        for section in seg.sections:
            if section.is_nobits:
                segments += (
                    f"      - {{ type: {section.splat_segment_type}, "
                    f"vram: 0x{section.vram:08X}, name: {seg.name}/{section.vram:08X} }} "
                    f"# {section.name}\n"
                )
            else:
                segments += (
                    f"      - [0x{section.start:06X}, {section.splat_segment_type}, "
                    f"{seg.name}/{section.start:06X}] # {section.name}\n"
                )
    segments += f"\n  - [0x{elf.size:X}]\n"

    os.makedirs(os.path.dirname(os.path.abspath(out_yaml)), exist_ok=True)
    with open(out_yaml, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
        f.write(segments)
    print(f"wrote {out_yaml}")
    print(f"  compiler={elf.compiler}  gp={elf.gp}  size=0x{elf.size:X}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        raise SystemExit(2)
    main(sys.argv[1], sys.argv[2], sys.argv[3])
